/**
 * Палитра категорий для диаграмм: цвета раздаются по порядку слотов и не
 * повторяются — так «Телефон» не меняет цвет от того, что выше добавили
 * строку. Первый слот — фирменный изумруд Global Expo, дальше — проверенная
 * эталонная восьмёрка. Порядок прогнан валидатором палитр на белой подложке:
 * худшая соседняя пара при дальтонизме ΔE 9.1 (цель ≥ 8), при обычном
 * зрении — 19.6. Бирюзовый, жёлтый и розовый светлее 3:1 к фону, поэтому
 * сектора всегда идут с подписями значений рядом.
 */
export const CHART_COLORS = [
  '#0e7745', // изумрудный — фирменный Global Expo
  '#2a78d6', // синий
  '#eb6834', // оранжевый
  '#1baf7a', // бирюзовый
  '#eda100', // жёлтый
  '#e87ba4', // розовый
  '#4a3aa7', // фиолетовый
  '#e34948', // красный
]

/** Серый для хвоста: девятая и дальше категории — «прочее». */
const REST_COLOR = '#8a958f'

/**
 * Цвет сектора: свой из данных, иначе слот по порядку. Дальше восьмого
 * новый оттенок не выдумываем — такие доли читаются только по подписи.
 */
export const colorAt = (item, index) =>
  item?.color ?? CHART_COLORS[index] ?? REST_COLOR
